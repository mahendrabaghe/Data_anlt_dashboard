"""
customer_segmentation.py
------------------------
RFM-based customer segmentation.
Segments customers into: VIP, Loyal, Potential Loyal,
New, At-Risk, and Lost.
"""

import pandas as pd
import numpy as np
from pathlib import Path
from datetime import datetime


PROJECT_ROOT = Path(__file__).resolve().parent.parent
CLEAN_PATH   = PROJECT_ROOT / "data" / "processed" / "cleaned_sales.csv"

# Snapshot date = the day after the latest order date in the dataset
SNAPSHOT_DATE: pd.Timestamp | None = None


# ──────────────────────────────────────────────────────────────
# RFM Calculation
# ──────────────────────────────────────────────────────────────
def calculate_rfm(df: pd.DataFrame) -> pd.DataFrame:
    """
    Compute Recency, Frequency, and Monetary value for every customer.

    - Recency   : Days since the customer's last order (lower = better)
    - Frequency : Number of distinct orders placed
    - Monetary  : Total revenue generated by the customer
    """
    global SNAPSHOT_DATE
    SNAPSHOT_DATE = df["Order_Date"].max() + pd.Timedelta(days=1)

    rfm = (
        df.groupby("Customer_ID")
          .agg(
              Last_Order_Date = ("Order_Date",  "max"),
              Frequency       = ("Order_ID",    "nunique"),
              Monetary        = ("Sales",        "sum"),
          )
          .reset_index()
    )

    rfm["Recency"] = (SNAPSHOT_DATE - rfm["Last_Order_Date"]).dt.days

    # Attach customer name / demographic from first occurrence
    cust_info = (
        df.drop_duplicates("Customer_ID")
          [["Customer_ID", "Customer_Name", "Gender", "Age", "City", "State"]]
    )
    rfm = rfm.merge(cust_info, on="Customer_ID", how="left")

    return rfm


# ──────────────────────────────────────────────────────────────
# RFM Scoring (quintile-based)
# ──────────────────────────────────────────────────────────────
def score_rfm(rfm: pd.DataFrame) -> pd.DataFrame:
    """
    Assign R, F, M scores (1–5) using quintile binning.
    For Recency, a lower value is BETTER → scores are reversed.
    """
    rfm = rfm.copy()

    # Recency: fewer days → higher score
    rfm["R_Score"] = pd.qcut(
        rfm["Recency"], q=5, labels=[5, 4, 3, 2, 1], duplicates="drop"
    ).astype(int)

    # Frequency: more orders → higher score
    rfm["F_Score"] = pd.qcut(
        rfm["Frequency"].rank(method="first"), q=5, labels=[1, 2, 3, 4, 5], duplicates="drop"
    ).astype(int)

    # Monetary: more spend → higher score
    rfm["M_Score"] = pd.qcut(
        rfm["Monetary"].rank(method="first"), q=5, labels=[1, 2, 3, 4, 5], duplicates="drop"
    ).astype(int)

    rfm["RFM_Score"] = rfm["R_Score"] * 100 + rfm["F_Score"] * 10 + rfm["M_Score"]

    return rfm


# ──────────────────────────────────────────────────────────────
# Segment Assignment
# ──────────────────────────────────────────────────────────────
def assign_segments(rfm: pd.DataFrame) -> pd.DataFrame:
    """
    Map RFM scores to business segments.

    Segment definitions
    -------------------
    VIP Customers         : R>=4, F>=4, M>=4  (best customers)
    Loyal Customers       : F>=4, M>=3         (frequent, good spend)
    Potential Loyal       : R>=3, F>=2, M>=2   (recent, moderate engagement)
    New Customers         : R>=4, F==1          (recent, only one order)
    At-Risk Customers     : R in [2,3], F>=3   (used to buy, drifting)
    Lost Customers        : R==1               (haven't ordered in a long time)
    """
    def _label(row: pd.Series) -> str:
        r, f, m = row["R_Score"], row["F_Score"], row["M_Score"]
        if   r >= 4 and f >= 4 and m >= 4:
            return "VIP Customers"
        elif f >= 4 and m >= 3:
            return "Loyal Customers"
        elif r >= 3 and f >= 2 and m >= 2:
            return "Potential Loyal"
        elif r >= 4 and f == 1:
            return "New Customers"
        elif r in (2, 3) and f >= 3:
            return "At-Risk Customers"
        else:
            return "Lost Customers"

    rfm = rfm.copy()
    rfm["Segment"] = rfm.apply(_label, axis=1)
    return rfm


# ──────────────────────────────────────────────────────────────
# Segment summary statistics
# ──────────────────────────────────────────────────────────────
def segment_summary(rfm: pd.DataFrame) -> pd.DataFrame:
    """Aggregate RFM metrics by segment."""
    summary = (
        rfm.groupby("Segment")
           .agg(
               Customers       = ("Customer_ID",   "count"),
               Avg_Recency     = ("Recency",        "mean"),
               Avg_Frequency   = ("Frequency",      "mean"),
               Total_Revenue   = ("Monetary",       "sum"),
               Avg_Revenue     = ("Monetary",       "mean"),
           )
           .reset_index()
    )

    # Segment order for display
    order = ["VIP Customers","Loyal Customers","Potential Loyal",
             "New Customers","At-Risk Customers","Lost Customers"]
    summary["Segment"] = pd.Categorical(summary["Segment"], categories=order, ordered=True)
    summary = summary.sort_values("Segment").reset_index(drop=True)

    for col in ["Avg_Recency","Avg_Frequency","Total_Revenue","Avg_Revenue"]:
        summary[col] = summary[col].round(1)

    return summary


# ──────────────────────────────────────────────────────────────
# Pipeline entry point
# ──────────────────────────────────────────────────────────────
def run_segmentation(df: pd.DataFrame) -> tuple:
    """
    Full RFM pipeline.

    Returns
    -------
    rfm_df  : pd.DataFrame  – per-customer RFM scores + segment
    summary : pd.DataFrame  – aggregated segment statistics
    """
    rfm = calculate_rfm(df)
    rfm = score_rfm(rfm)
    rfm = assign_segments(rfm)
    summary = segment_summary(rfm)
    return rfm, summary


# ──────────────────────────────────────────────────────────────
# Standalone execution
# ──────────────────────────────────────────────────────────────
if __name__ == "__main__":
    df = pd.read_csv(CLEAN_PATH, parse_dates=["Order_Date"])
    rfm_df, summary = run_segmentation(df)

    print("\n=== RFM SEGMENT SUMMARY ===")
    print(summary.to_string(index=False))
    print(f"\nSnapshot date : {SNAPSHOT_DATE.date()}")

    out_path = PROJECT_ROOT / "data" / "processed" / "customer_segments.csv"
    rfm_df.to_csv(out_path, index=False)
    print(f"\nCustomer segments saved to: {out_path}")
